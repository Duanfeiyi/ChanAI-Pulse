function prediction = run_v31_product_safety_gate( ...
        extraction, task, config)
%RUN_V31_PRODUCT_SAFETY_GATE Invoke known-region backtest and prediction.

arguments
    extraction (1, 1) struct
    task (1, 1) struct
    config (1, 1) struct = struct()
end

config = fillConfig(config);
sequence = extraction.sequence;
taskType = taskTypeOf(task);
registryPath = fullfile(config.registry_root, taskType, ...
    taskType + "_model_registry_v2.json");
root = fileparts(fileparts(fileparts(mfilename("fullpath"))));
scriptPath = fullfile(root, "tools", "python", ...
    "run_v31_product_gate.py");
inputPath = string(tempname) + ".json";
outputPath = string(tempname) + ".json";
cleanup = onCleanup(@() cleanupFiles([inputPath, outputPath]));
payload = struct( ...
    "schema_version", "v3.1-product-p8-gate-input.1", ...
    "task_type", taskType, ...
    "parameter_names", sequence.parameter_names, ...
    "parameter_units", sequence.parameter_units, ...
    "known_values", sequence.values, ...
    "known_parameter_sample_index", sequence.parameter_sample_index, ...
    "known_group_id", sequence.group_id, ...
    "known_quality_status", sequence.quality_status, ...
    "locally_observed_parameter_names", ...
        sequence.provenance.locally_observed_parameter_names, ...
    "imputed_parameter_names", ...
        sequence.provenance.imputed_parameter_names, ...
    "target_parameter_sample_index", double(task.target_indices(:)).', ...
    "selection_mode", config.selection_mode, ...
    "requested_model", config.requested_model, ...
    "adaptation_mode", config.adaptation_mode, ...
    "device", config.device, ...
    "registry_path", registryPath, ...
    "gate", config.gate);
writeJson(inputPath, payload);
parts = [quote(config.python_executable), quote(scriptPath), ...
    "--input", quote(inputPath), "--output", quote(outputPath)];
[status, commandOutput] = system(strjoin(parts, " "));
if status ~= 0
    error("run_v31_product_safety_gate:PythonFailure", ...
        "Known-region model safety gate failed (exit %d): %s", ...
        status, strtrim(commandOutput));
end
if ~isfile(outputPath)
    error("run_v31_product_safety_gate:MissingOutput", ...
        "The product gate did not create its result JSON.");
end
prediction = jsondecode(fileread(outputPath));
prediction.parameter_names = string(prediction.parameter_names(:));
prediction.parameter_units = string(prediction.parameter_units(:));
targetCount = numel(task.target_indices);
prediction.prediction_parameters = reshape( ...
    double(prediction.prediction_parameters), [1, targetCount, 8]);
prediction.target_parameter_sample_index = reshape( ...
    double(prediction.target_parameter_sample_index), [1, targetCount]);
prediction.selection.selected_model_type = ...
    string(prediction.selection.selected_model);
prediction.model.model_type = string(prediction.selection.selected_model);
knownValues = double(prediction.known_context_parameters);
prediction.known_context_parameters = reshape( ...
    knownValues, [numel(knownValues) / 8, 8]);
prediction.known_context_parameter_sample_index = double( ...
    prediction.known_context_parameter_sample_index(:));
prediction.provenance = sequence.provenance;
prediction.provenance.extraction_schema_version = extraction.schema_version;
prediction.provenance.valid_fitted_row_count = extraction.valid_row_count;
prediction.provenance.target_channel_samples_read = false;
prediction.model.product_input_provenance = prediction.provenance;

names = string(prediction.parameter_names(:)).';
values = reshape(prediction.prediction_parameters, [targetCount, 8]);
countColumns = find(ismember(names, ["num_clusters", "num_rays"]));
before = values(:, countColumns);
values(:, countColumns) = round(values(:, countColumns));
prediction.prediction_parameters = reshape(values, [1, targetCount, 8]);
if ~isfield(prediction, "postprocessing") || ...
        ~isstruct(prediction.postprocessing)
    prediction.postprocessing = struct();
end
prediction.postprocessing.schema_version = ...
    "v3.1-generator-parameter-projection.3";
prediction.postprocessing.integer_parameter_names = names(countColumns);
prediction.postprocessing.integer_rule = ...
    "nearest_integer_after_registry_bound_projection";
prediction.postprocessing.integer_changed_value_count = ...
    sum(before ~= values(:, countColumns), "all");
prediction.model.product_postprocessing = prediction.postprocessing;
prediction.adapter = struct( ...
    "schema_version", "v3.1-matlab-product-safety-gate-adapter.1", ...
    "python_command_status", status, ...
    "python_summary", string(strtrim(commandOutput)));
end

function config = fillConfig(config)
root = fileparts(fileparts(fileparts(mfilename("fullpath"))));
defaults = struct( ...
    "registry_root", fullfile(root, "models", "official", "v3.1.0"), ...
    "python_executable", "python", ...
    "selection_mode", "auto", ...
    "requested_model", "", ...
    "adaptation_mode", "auto", ...
    "device", "auto", ...
    "gate", struct( ...
        "maximum_baseline_regret", 0.10, ...
        "maximum_worst_example_ratio", 1.50, ...
        "maximum_parameter_regret_ratio", 2.00, ...
        "maximum_absolute_normalized_rmse", 2.00, ...
        "maximum_absolute_worst_example_normalized_rmse", 3.00, ...
        "neural_auto_minimum_improvement", 0.05, ...
        "maximum_continuity_ratio", 3.0, ...
        "minimum_backtest_examples", 3));
for name = string(fieldnames(defaults)).'
    if ~isfield(config, name)
        config.(name) = defaults.(name);
    end
end
end

function value = taskTypeOf(task)
if isfield(task, "task_type")
    value = string(task.task_type);
else
    value = string(task.mode);
end
end

function writeJson(path, value)
identifier = fopen(path, "w", "n", "UTF-8");
if identifier < 0
    error("run_v31_product_safety_gate:WriteFailed", ...
        "Could not create temporary product-gate input.");
end
cleanup = onCleanup(@() fclose(identifier));
fprintf(identifier, "%s", jsonencode(value));
end

function value = quote(value)
value = string(value);
value = replace(value, """", """""");
value = """" + value + """";
end

function cleanupFiles(paths)
for path = string(paths(:)).'
    if isfile(path)
        delete(path);
    end
end
end
