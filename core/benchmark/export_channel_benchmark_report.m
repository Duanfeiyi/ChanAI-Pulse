function files = export_channel_benchmark_report(result, outputRoot)
%EXPORT_CHANNEL_BENCHMARK_REPORT Write CSV, Markdown, PNG and manifest.

arguments
    result (1, 1) struct
    outputRoot (1, 1) string
end
if outputRoot == ""
    outputRoot = fullfile(pwd, "benchmark_outputs");
end
if ~isfolder(outputRoot), mkdir(outputRoot); end
stamp = string(datetime("now", "Format", "yyyyMMdd_HHmmss_SSS"));
outputDirectory = fullfile(outputRoot, "benchmark_" + stamp);
if isfolder(outputDirectory)
    error("export_channel_benchmark_report:OutputExists", ...
        "Refusing to overwrite %s.", outputDirectory);
end
mkdir(outputDirectory);

files = struct( ...
    "output_directory", outputDirectory, ...
    "summary_csv", fullfile(outputDirectory, "benchmark_summary.csv"), ...
    "per_target_csv", fullfile(outputDirectory, "benchmark_per_target.csv"), ...
    "per_link_csv", fullfile(outputDirectory, "benchmark_per_link.csv"), ...
    "report_markdown", fullfile(outputDirectory, "benchmark_report.md"), ...
    "metrics_png", fullfile(outputDirectory, "benchmark_metrics.png"), ...
    "target_png", fullfile(outputDirectory, "benchmark_per_target.png"), ...
    "manifest_json", fullfile(outputDirectory, "benchmark_manifest.json"));

prediction = result.metrics.prediction;
persistence = result.metrics.persistence;
linear = result.metrics.linear;
summary = table( ...
    ["Prediction"; "Persistence"; "Linear"], ...
    [prediction.complex_nmse; persistence.complex_nmse; linear.complex_nmse], ...
    [prediction.magnitude_nrmse; persistence.magnitude_nrmse; linear.magnitude_nrmse], ...
    [prediction.phase_mae_rad; persistence.phase_mae_rad; linear.phase_mae_rad], ...
    [prediction.complex_correlation; persistence.complex_correlation; linear.complex_correlation], ...
    [prediction.pdp_nrmse; persistence.pdp_nrmse; linear.pdp_nrmse], ...
    [prediction.rms_delay_spread_abs_error_s; ...
        persistence.rms_delay_spread_abs_error_s; linear.rms_delay_spread_abs_error_s], ...
    [prediction.evaluation_runtime_s; persistence.evaluation_runtime_s; ...
        linear.evaluation_runtime_s], ...
    [prediction.generation_runtime_s; persistence.generation_runtime_s; ...
        linear.generation_runtime_s], ...
    'VariableNames', {'Method', 'ComplexNMSE', 'MagnitudeNRMSE', ...
        'PhaseMAERad', 'ComplexCorrelation', 'PDPNRMSE', ...
        'RMSDelaySpreadAbsErrorS', 'EvaluationRuntimeS', 'GenerationRuntimeS'});
writetable(summary, files.summary_csv);
writetable(struct2table(result.per_target), files.per_target_csv);
writetable(struct2table(result.per_link), files.per_link_csv);

figureHandle = figure("Visible", "off", "Color", "white", ...
    "Position", [100, 100, 1000, 520]);
cleanupFigure = onCleanup(@() delete(figureHandle));
subplot(1, 2, 1);
bar(categorical(summary.Method), summary.ComplexNMSE);
set(gca, "YScale", "log"); ylabel("Complex NMSE (lower is better)");
title("Prediction vs baselines"); grid on;
subplot(1, 2, 2);
bar(categorical(summary.Method), summary.ComplexCorrelation);
ylim([0, 1]); ylabel("Complex correlation (higher is better)");
title("Complex correlation"); grid on;
exportgraphics(figureHandle, files.metrics_png, "Resolution", 160);
clear cleanupFigure

targetTable = struct2table(result.per_target);
figureHandle = figure("Visible", "off", "Color", "white", ...
    "Position", [100, 100, 1000, 520]);
cleanupFigure = onCleanup(@() delete(figureHandle));
semilogy(targetTable.axis_value, targetTable.prediction_complex_nmse, ...
    "-o", "LineWidth", 1.5); hold on;
semilogy(targetTable.axis_value, targetTable.persistence_complex_nmse, "--s");
semilogy(targetTable.axis_value, targetTable.linear_complex_nmse, ":^");
xlabel("Target task-axis value"); ylabel("Complex NMSE");
legend("Prediction", "Persistence", "Linear", "Location", "best");
title("Per-target comparison"); grid on;
exportgraphics(figureHandle, files.target_png, "Resolution", 160);
clear cleanupFigure

writeMarkdown(files.report_markdown, result, summary);
manifest = rmfield(result, ["per_target", "per_link"]);
manifest.files = files;
writeJson(files.manifest_json, manifest);
end

function writeMarkdown(path, result, summary)
lines = [ ...
    "# ChanAI Pulse v3.0 Benchmark Report"; ""; ...
    "- Comparability: **" + result.comparability_status + "**"; ...
    "- Prediction quality versus best baseline: **" + result.quality_label + "**"; ...
    "- Best baseline: **" + result.best_baseline + "**"; ...
    "- Target ground truth was used only by the Benchmark: **yes**"; ""; ...
    "## Main metrics"; ""; ...
    "| Method | Complex NMSE | Magnitude NRMSE | Phase MAE (rad) | Correlation | PDP NRMSE |"; ...
    "|---|---:|---:|---:|---:|---:|"];
for index = 1:height(summary)
    lines(end + 1, 1) = sprintf("| %s | %.6g | %.6g | %.6g | %.6g | %.6g |", ...
        summary.Method(index), summary.ComplexNMSE(index), ...
        summary.MagnitudeNRMSE(index), summary.PhaseMAERad(index), ...
        summary.ComplexCorrelation(index), summary.PDPNRMSE(index)); %#ok<AGROW>
end
lines = [lines; ""; "## Reading rule"; ""; ...
    "PASS means the two inputs are aligned and comparable; it does not mean prediction accuracy is good."; ...
    "Lower error metrics are better. Complex correlation is better when closer to 1."; ...
    "The software intentionally does not invent one universal accuracy percentage."];
writeText(path, strjoin(lines, newline));
end

function writeJson(path, value)
writeText(path, jsonencode(value, PrettyPrint=true));
end

function writeText(path, value)
identifier = fopen(path, "w", "n", "UTF-8");
if identifier < 0
    error("export_channel_benchmark_report:WriteFailed", ...
        "Could not write %s.", path);
end
cleanup = onCleanup(@() fclose(identifier));
fprintf(identifier, "%s", value);
clear cleanup
end
