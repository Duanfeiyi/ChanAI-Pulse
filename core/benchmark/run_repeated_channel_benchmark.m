function result = run_repeated_channel_benchmark( ...
        originalFile, predictionDirectories, config)
%RUN_REPEATED_CHANNEL_BENCHMARK Aggregate independent stochastic exports.
%   Each directory must be a complete export of the same task. This entry
%   does not regenerate channels or alter seeds; it evaluates realizations
%   that were independently produced by ChannelSimulator/generator calls.

arguments
    originalFile (1, 1) string
    predictionDirectories (:, 1) string
    config (1, 1) struct = default_channel_benchmark_config()
end
if numel(predictionDirectories) < 2
    error("run_repeated_channel_benchmark:NeedMultipleExports", ...
        "At least two independent prediction export directories are required.");
end
if numel(unique(predictionDirectories)) ~= numel(predictionDirectories)
    error("run_repeated_channel_benchmark:DuplicateExport", ...
        "Repeated statistics require distinct prediction export directories.");
end
singleConfig = config;
singleConfig.repeat_count = 1;
singleConfig.export_report = false;
results = cell(numel(predictionDirectories), 1);
for index = 1:numel(predictionDirectories)
    results{index} = run_channel_benchmark(originalFile, ...
        predictionDirectories(index), singleConfig);
    if index > 1
        assertSameTask(results{1}, results{index});
    end
end

metricNames = string(fieldnames(results{1}.metrics.prediction));
aggregate = struct();
perRepeat = repmat(struct("repeat", 0, "prediction_directory", "", ...
    "quality_label", "", "complex_nmse", NaN, ...
    "complex_correlation", NaN, "generation_runtime_s", NaN), ...
    numel(results), 1);
for metricName = metricNames.'
    values = NaN(numel(results), 1);
    for index = 1:numel(results)
        value = results{index}.metrics.prediction.(metricName);
        if isnumeric(value) && isscalar(value), values(index) = double(value); end
    end
    finite = values(isfinite(values));
    if isempty(finite)
        aggregate.(metricName) = struct("mean", NaN, "std", NaN, ...
            "minimum", NaN, "maximum", NaN, "available_count", 0);
    else
        aggregate.(metricName) = struct("mean", mean(finite), ...
            "std", std(finite, 0), "minimum", min(finite), ...
            "maximum", max(finite), "available_count", numel(finite));
    end
end
for index = 1:numel(results)
    metric = results{index}.metrics.prediction;
    perRepeat(index) = struct("repeat", index, ...
        "prediction_directory", predictionDirectories(index), ...
        "quality_label", results{index}.quality_label, ...
        "complex_nmse", metric.complex_nmse, ...
        "complex_correlation", metric.complex_correlation, ...
        "generation_runtime_s", metric.generation_runtime_s);
end
result = struct( ...
    "schema_version", "v3.0-repeated-channel-benchmark.1", ...
    "created_utc", utcNow(), "repeat_count", numel(results), ...
    "comparability_status", "PASS", ...
    "task", results{1}.task, "aggregate", aggregate, ...
    "per_repeat", perRepeat, "single_results", {results}, ...
    "master_seed", config.master_seed, ...
    "explanation", ...
        "Mean/std describe independently exported stochastic realizations.");
end

function assertSameTask(reference, candidate)
if string(reference.task.mode) ~= string(candidate.task.mode) || ...
        string(reference.task.axis) ~= string(candidate.task.axis) || ...
        ~isequal(double(reference.task.known_indices(:)), ...
            double(candidate.task.known_indices(:))) || ...
        ~isequal(double(reference.task.target_indices(:)), ...
            double(candidate.task.target_indices(:))) || ...
        ~isequal(double(reference.representation.shape), ...
            double(candidate.representation.shape))
    error("run_repeated_channel_benchmark:TaskMismatch", ...
        "All repeated exports must describe the same aligned task and dimensions.");
end
end

function value = utcNow()
value = string(datetime("now", "TimeZone", "UTC", ...
    "Format", "yyyy-MM-dd'T'HH:mm:ss.SSS'Z'"));
end
