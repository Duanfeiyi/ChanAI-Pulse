function report = probe_v32_4b_benchmark_three_axis(engineRoot)
%PROBE_V32_4B_BENCHMARK_THREE_AXIS v3.2-4b three-axis end-to-end Benchmark.
%   For each axis (time/space/frequency), runs the real product prediction
%   chain against the probe import files (which carry full ground truth),
%   exports the prediction bundle, and evaluates it with the independent
%   run_channel_benchmark. Verifies that the benchmark aligns and scores
%   time/space/frequency tasks. Time/Space need the Full 6GPCM engine.

arguments
    engineRoot (1, 1) string = ""
end

repoRoot = fileparts(fileparts(fileparts(mfilename("fullpath"))));
addpath(fullfile(repoRoot, "core"));
addpath(genpath(fullfile(repoRoot, "core")));

if engineRoot == ""
    engineRoot = resolve_full_6gpcm_root().root;
end
probeDir = fullfile(tempdir, "v32_4_probe_import");
if ~isfolder(probeDir)
    mkdir(probeDir);
end
export_v32_4_probe_import_files(probeDir);
frozen = struct("DS_sigma", 0.35, "KF_sigma", 2.0, "r_DS", 2.66, ...
    "LNS_ksi", 3.33, "num_clusters", 12, "num_rays", 20);
calibration = struct("success", true, ...
    "best", struct("parameters", frozen), ...
    "manifest", struct("schema_version", "v3.2-4b-test"));

report = struct("schema_version", "v3.2-4b-three-axis-benchmark.1");
cases = { ...
    struct("name", "time", ...
        "file", fullfile(probeDir, "v32_4_time_import.h5"), ...
        "axis", "time", "mode", "extrapolation", ...
        "known", (1:16).', "target", (17:20).', ...
        "generation", true); ...
    struct("name", "space", ...
        "file", fullfile(probeDir, "v32_4_space_import.h5"), ...
        "axis", "space", "mode", "extrapolation", ...
        "known", (1:16).', "target", (17:20).', ...
        "generation", true); ...
    struct("name", "frequency", ...
        "file", fullfile(probeDir, "v32_4_frequency_import.h5"), ...
        "axis", "frequency", "mode", "interpolation", ...
        "known", [1:28, 37:64].', "target", (29:36).', ...
        "generation", false)};

for caseIndex = 1:numel(cases)
    item = cases{caseIndex};
    fprintf("==== %s axis benchmark ====\n", item.name);
    imported = import_channel_dataset(item.file, struct( ...
        "task_mode", item.mode, "task_axis", item.axis, ...
        "task_preset", "manual", ...
        "known_indices", item.known, "target_indices", item.target));
    assert(imported.status == "PASS", "import failed for %s", item.name);

    prediction = run_v32_axis_prediction(imported.dataset, calibration, ...
        imported.task, "full_6gpcm", struct());
    if item.generation
        generationConfig = default_prediction_generation_config("full_6gpcm");
        if item.axis == "space"
            generationConfig.task_axis = "position";
        else
            generationConfig.task_axis = item.axis;
        end
        generationConfig.task_axis_unit = ...
            string(imported.task.axis_unit);
        generationConfig.target_axis_values = ...
            double(imported.task.axis_values(item.target));
        generationConfig.dimensions.Tx = imported.dataset.dimensions.Tx;
        generationConfig.dimensions.Rx = imported.dataset.dimensions.Rx;
        generationConfig.dimensions.Nt = 1;
        generationConfig.dimensions.Npath = 400;
        generationConfig.parameter_sources.calibrated = frozen;
        generationConfig.generator_overrides.backend_options = struct( ...
            "full_interface", "public_api", ...
            "full_track_speed_mps", 8.0);
        request = create_prediction_generation_request( ...
            prediction, generationConfig);
        service = run_prediction_generation(request, struct());
        assert(service.success, "generation failed for %s: %s", ...
            item.name, strjoin(service.errors, " | "));
        predictionResult = service.prediction_result;
    else
        service = run_v32_frequency_generation( ...
            imported.dataset, prediction, struct());
        assert(service.success, "frequency recovery failed: %s", ...
            strjoin(service.errors, " | "));
        predictionResult = service.prediction_result;
    end

    predictionResult.benchmark_context = struct( ...
        "schema_version", "v3.0-benchmark-context.1", ...
        "task", imported.task, ...
        "original_dimensions", imported.dataset.dimensions, ...
        "original_schema_version", imported.dataset.schema_version, ...
        "original_file_sha256", compute_benchmark_file_sha256(item.file), ...
        "target_ground_truth_read_by_prediction", false);

    outputRoot = fullfile(tempdir, "v32_4b_benchmark_" + item.name);
    if isfolder(outputRoot)
        rmdir(outputRoot, "s");
    end
    mkdir(outputRoot);
    predictionDirectory = fullfile(outputRoot, "prediction_export");
    export_prediction_result_bundle(predictionResult, predictionDirectory);

    config = default_channel_benchmark_config();
    config.export_report = true;
    config.output_root = fullfile(outputRoot, "reports");
    result = run_channel_benchmark(item.file, predictionDirectory, config);
    assert(result.comparability_status == "PASS", ...
        "comparability failed for %s", item.name);
    metrics = result.metrics.prediction;
    assert(isfinite(metrics.complex_nmse), ...
        "complex_nmse must be finite for %s", item.name);
    report.(item.name) = struct( ...
        "comparability_status", string(result.comparability_status), ...
        "quality_label", string(result.quality_label), ...
        "complex_nmse", metrics.complex_nmse, ...
        "complex_nrmse", metrics.complex_nrmse, ...
        "complex_correlation", metrics.complex_correlation, ...
        "magnitude_nrmse", metrics.magnitude_nrmse, ...
        "phase_mae_rad", metrics.phase_mae_rad, ...
        "pdp_nrmse", metrics.pdp_nrmse, ...
        "spatial_correlation_nrmse", metrics.spatial_correlation_nrmse, ...
        "time_autocorrelation_nrmse", metrics.time_autocorrelation_nrmse, ...
        "target_count", numel(item.target));
    fprintf("  %s: comparability=%s quality=%s complex_nmse=%.4f\n", ...
        item.name, report.(item.name).comparability_status, ...
        report.(item.name).quality_label, report.(item.name).complex_nmse);
end

fprintf("PASS: v3.2-4b three-axis benchmark.\n");
end
