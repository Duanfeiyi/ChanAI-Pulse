function request = create_prediction_generation_request(prediction, config)
%CREATE_PREDICTION_GENERATION_REQUEST Select one prediction example.
%   Step 10 can return a batch. Step 11 generates the four target points of
%   one selected example and never reads target ground truth.

arguments
    prediction (1, 1) struct
    config (1, 1) struct = default_prediction_generation_config()
end

config = mergeStruct(default_prediction_generation_config( ...
    requestedBackend(config)), config);
requiredPredictionFields = ["schema_version", "task_type", ...
    "parameter_names", "parameter_units", "prediction_parameters", ...
    "target_parameter_sample_index", "selection", "adaptation", "model"];
missing = requiredPredictionFields( ...
    ~isfield(prediction, requiredPredictionFields));
if ~isempty(missing)
    error("create_prediction_generation_request:MissingPredictionField", ...
        "Prediction is missing fields: %s.", strjoin(missing, ", "));
end
if isfield(prediction, "request_contains_target_ground_truth") && ...
        logical(prediction.request_contains_target_ground_truth)
    error("create_prediction_generation_request:UnsafePrediction", ...
        "Product prediction must not contain target ground truth.");
end

values = double(prediction.prediction_parameters);
if ndims(values) ~= 3
    error("create_prediction_generation_request:InvalidPredictionShape", ...
        "prediction_parameters must be [N_example, N_target, N_parameter].");
end
exampleIndex = double(config.prediction_example_index);
if ~isscalar(exampleIndex) || ~isfinite(exampleIndex) || ...
        exampleIndex < 1 || floor(exampleIndex) ~= exampleIndex || ...
        exampleIndex > size(values, 1)
    error("create_prediction_generation_request:InvalidExampleIndex", ...
        "prediction_example_index must select one available example.");
end

parameterNames = string(prediction.parameter_names(:));
parameterUnits = string(prediction.parameter_units(:));
selectedValues = reshape(values(exampleIndex, :, :), ...
    [size(values, 2), size(values, 3)]);
targetIndexAll = double(prediction.target_parameter_sample_index);
selectedTargetIndex = reshape(targetIndexAll(exampleIndex, :), [], 1);
targetAxisValues = double(config.target_axis_values);
if isempty(targetAxisValues)
    targetAxisValues = selectedTargetIndex;
else
    targetAxisValues = targetAxisValues(:);
end
if numel(targetAxisValues) ~= size(selectedValues, 1)
    error("create_prediction_generation_request:TargetAxisMismatch", ...
        "target_axis_values must have one value per predicted target.");
end

request = struct( ...
    "schema_version", "v3.0-prediction-generation-request.1", ...
    "created_utc", utcNow(), ...
    "task_type", string(prediction.task_type), ...
    "task_axis", string(config.task_axis), ...
    "task_axis_unit", string(config.task_axis_unit), ...
    "prediction_example_index", exampleIndex, ...
    "parameter_names", parameterNames, ...
    "parameter_units", parameterUnits, ...
    "predicted_parameters", selectedValues, ...
    "target_parameter_sample_index", selectedTargetIndex, ...
    "target_axis_values", targetAxisValues, ...
    "target_count", size(selectedValues, 1), ...
    "dimensions", config.dimensions, ...
    "scenario", config.scenario, ...
    "ctf", config.ctf, ...
    "backend", string(config.backend), ...
    "mode", string(config.mode), ...
    "master_seed", double(config.master_seed), ...
    "parameter_sources", config.parameter_sources, ...
    "parameter_bounds", config.parameter_bounds, ...
    "generator_overrides", config.generator_overrides, ...
    "engine_root", string(config.engine_root), ...
    "engine", config.engine, ...
    "continuity", string(config.continuity), ...
    "runtime", config.runtime, ...
    "prediction_manifest", struct( ...
        "schema_version", string(prediction.schema_version), ...
        "selection", prediction.selection, ...
        "adaptation", prediction.adaptation, ...
        "model", prediction.model, ...
        "request_contains_target_ground_truth", false));
end

function backend = requestedBackend(config)
backend = "mock";
if isstruct(config) && isscalar(config) && isfield(config, "backend")
    backend = string(config.backend);
end
end

function output = mergeStruct(defaults, supplied)
output = defaults;
for nameCell = fieldnames(supplied).'
    name = nameCell{1};
    if isfield(output, name) && isstruct(output.(name)) && ...
            isscalar(output.(name)) && isstruct(supplied.(name)) && ...
            isscalar(supplied.(name))
        output.(name) = mergeStruct(output.(name), supplied.(name));
    else
        output.(name) = supplied.(name);
    end
end
end

function value = utcNow()
value = string(datetime("now", "TimeZone", "UTC", ...
    "Format", "yyyy-MM-dd'T'HH:mm:ss.SSS'Z'"));
end
