function [dataset, manifest] = combine_prediction_target_cir( ...
        targetResults, request)
%COMBINE_PREDICTION_TARGET_CIR Pad and combine per-target CIR datasets.

arguments
    targetResults (:, 1) cell
    request (1, 1) struct
end

targetCount = numel(targetResults);
if targetCount ~= request.target_count || targetCount == 0
    error("combine_prediction_target_cir:TargetCountMismatch", ...
        "All requested targets must be present before combination.");
end
pathCounts = zeros(targetCount, 1);
for index = 1:targetCount
    item = targetResults{index};
    if ~isstruct(item) || ~item.success || ...
            ~isfield(item, "dataset") || ...
            string(item.dataset.domain) ~= "cir"
        error("combine_prediction_target_cir:InvalidTarget", ...
            "Target %d is not a successful CIR result.", index);
    end
    pathCounts(index) = item.dataset.dimensions.Npath;
end

txCount = request.dimensions.Tx;
rxCount = request.dimensions.Rx;
timeCount = request.dimensions.Nt;
maxPathCount = max(pathCounts);
shape = [txCount, rxCount, maxPathCount, timeCount, targetCount];
coefficient = complex(zeros(shape));
delayS = zeros(shape);
pathValid = false(shape);
optional = ["aoa_rad", "aod_rad", "doppler_hz"];
includeOptional = false(size(optional));
optionalData = cell(size(optional));
for fieldIndex = 1:numel(optional)
    includeOptional(fieldIndex) = all(cellfun( ...
        @(item) isfield(item.dataset.cir, optional(fieldIndex)), ...
        targetResults));
    if includeOptional(fieldIndex)
        optionalData{fieldIndex} = zeros(shape);
    end
end

for targetNumber = 1:targetCount
    source = targetResults{targetNumber}.dataset.cir;
    pathCount = pathCounts(targetNumber);
    coefficient(:, :, 1:pathCount, :, targetNumber) = ...
        source.coefficient(:, :, :, :, 1);
    expandedDelay = expandField(source.delay_s, ...
        size5(source.coefficient));
    expandedValid = expandField(source.path_valid, ...
        size5(source.coefficient));
    delayS(:, :, 1:pathCount, :, targetNumber) = ...
        expandedDelay(:, :, :, :, 1);
    pathValid(:, :, 1:pathCount, :, targetNumber) = ...
        expandedValid(:, :, :, :, 1);
    for fieldIndex = 1:numel(optional)
        if includeOptional(fieldIndex)
            expanded = expandField(source.(optional(fieldIndex)), ...
                size5(source.coefficient));
            optionalData{fieldIndex}(:, :, 1:pathCount, :, targetNumber) = ...
                expanded(:, :, :, :, 1);
        end
    end
end

payload = struct("coefficient", coefficient, ...
    "delay_s", delayS, "path_valid", pathValid);
for fieldIndex = 1:numel(optional)
    if includeOptional(fieldIndex)
        payload.(optional(fieldIndex)) = optionalData{fieldIndex};
    end
end
axes = struct( ...
    "sample_index", double(request.target_parameter_sample_index(:)), ...
    "time_s", (0:timeCount - 1).' * ...
        double(request.scenario.snapshot_interval_s));
if request.task_axis == "position"
    axes.sample_position_m = double(request.target_axis_values(:));
end
metadata = struct( ...
    "source", "step11_predicted_target_cir", ...
    "sample_semantics", "independent", ...
    "target_continuity", request.continuity, ...
    "target_axis", request.task_axis, ...
    "target_axis_unit", request.task_axis_unit, ...
    "target_axis_values", double(request.target_axis_values(:)), ...
    "generator", request.engine.id, ...
    "generator_version", request.engine.version, ...
    "center_frequency_hz", request.scenario.center_frequency_hz, ...
    "frequency_count", request.dimensions.Nf, ...
    "subcarrier_spacing_hz", frequencySpacing(request), ...
    "snapshot_interval_s", request.scenario.snapshot_interval_s, ...
    "scenario_id", request.scenario.id, ...
    "master_seed", request.master_seed, ...
    "target_position_injected", false, ...
    "position_limitation", ...
        "Current generator API has no explicit target-coordinate input.", ...
    "prediction_schema_version", request.prediction_manifest.schema_version);
metadata = copyKnownArrayGeometry( ...
    metadata, targetResults{1}.dataset.metadata);
dataset = create_channel_dataset("cir", payload, axes, metadata);

manifest = struct( ...
    "schema_version", "v3.0-prediction-cir-combination.1", ...
    "target_count", targetCount, ...
    "target_order", double(request.target_parameter_sample_index(:)), ...
    "path_count_per_target", pathCounts, ...
    "padded_path_count", maxPathCount, ...
    "continuity", request.continuity, ...
    "target_position_injected", false, ...
    "all_or_nothing", true);
end

function metadata = copyKnownArrayGeometry(metadata, source)
for name = ["tx_array", "rx_array"]
    if isfield(source, name)
        metadata.(name) = source.(name);
    end
end
end

function spacing = frequencySpacing(request)
spacing = request.scenario.bandwidth_hz / max(request.dimensions.Nf, 1);
if request.ctf.enabled && numel(request.ctf.frequency_hz) > 1
    spacing = median(diff(double(request.ctf.frequency_hz(:))));
end
end

function expanded = expandField(value, targetSize)
sourceSize = size5(value);
if ~all(sourceSize == 1 | sourceSize == targetSize)
    error("combine_prediction_target_cir:CannotExpand", ...
        "CIR field cannot expand to coefficient dimensions.");
end
expanded = repmat(reshape(value, sourceSize), targetSize ./ sourceSize);
end

function shape = size5(value)
shape = [size(value, 1), size(value, 2), size(value, 3), ...
    size(value, 4), size(value, 5)];
end
