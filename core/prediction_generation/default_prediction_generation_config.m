function config = default_prediction_generation_config(backend)
%DEFAULT_PREDICTION_GENERATION_CONFIG Step 11 orchestration defaults.
%   The configuration joins one Step 10 parameter prediction to the shared
%   Step 6 Generator Adapter. Formal mode is reserved for full_6gpcm.

arguments
    backend (1, 1) string = "mock"
end

generator = default_generator_config(backend);
backend = generator.backend;
frequencyCount = 64;
frequencyHz = centeredFrequencyAxis( ...
    generator.scenario.center_frequency_hz, ...
    generator.scenario.bandwidth_hz, frequencyCount);

config = struct( ...
    "schema_version", "v3.0-prediction-generation-config.1", ...
    "backend", backend, ...
    "mode", "preview", ...
    "prediction_example_index", 1, ...
    "master_seed", 11100, ...
    "task_axis", "sample", ...
    "task_axis_unit", "index", ...
    "target_axis_values", zeros(0, 1), ...
    "dimensions", struct( ...
        "Tx", generator.dimensions.Tx, ...
        "Rx", generator.dimensions.Rx, ...
        "Nf", frequencyCount, ...
        "Nt", generator.dimensions.Nt, ...
        "Npath", generator.dimensions.Npath), ...
    "scenario", generator.scenario, ...
    "ctf", struct( ...
        "enabled", true, ...
        "frequency_hz", frequencyHz), ...
    "parameter_sources", struct( ...
        "calibrated", struct(), ...
        "scenario", struct(), ...
        "versioned_defaults", generator.model, ...
        "defaults_version", "v3.0-step11.1"), ...
    "parameter_bounds", defaultBounds(), ...
    "generator_overrides", struct(), ...
    "engine_root", generator.engine_root, ...
    "engine", generator.engine, ...
    "continuity", "independent_targets", ...
    "runtime", struct( ...
        "full_timeout_s", 300, ...
        "cache_enabled", false));
end

function bounds = defaultBounds()
bounds = struct( ...
    "DS_mu", [-12, -3], ...
    "DS_sigma", [0, 3], ...
    "r_DS", [eps, 20], ...
    "num_clusters", [1, 100], ...
    "num_rays", [1, 1000], ...
    "LNS_ksi", [eps, 50], ...
    "KF_mu", [-50, 50], ...
    "KF_sigma", [0, 50], ...
    "doppler_hz", [0, 1e6]);
end

function frequencyHz = centeredFrequencyAxis(centerHz, bandwidthHz, count)
if count == 1
    frequencyHz = centerHz;
    return;
end
spacingHz = bandwidthHz / count;
offset = ((0:count - 1).' - (count - 1) / 2) * spacingHz;
frequencyHz = centerHz + offset;
end
