function key = compute_prediction_generation_cache_key(request)
%COMPUTE_PREDICTION_GENERATION_CACHE_KEY Hash all result-defining inputs.

payload = struct( ...
    "request_schema", request.schema_version, ...
    "task_type", request.task_type, ...
    "prediction_model", request.prediction_manifest.model, ...
    "prediction_selection", request.prediction_manifest.selection, ...
    "predicted_parameters", request.predicted_parameters, ...
    "target_axis_values", request.target_axis_values, ...
    "backend", request.backend, ...
    "engine", request.engine, ...
    "scenario", request.scenario, ...
    "dimensions", request.dimensions, ...
    "ctf", request.ctf, ...
    "parameter_sources", request.parameter_sources, ...
    "master_seed", request.master_seed);
bytes = unicode2native(jsonencode(payload), "UTF-8");
digest = javaMethod("getInstance", ...
    "java.security.MessageDigest", "SHA-256");
digest.update(typecast(uint8(bytes(:)), "int8"));
raw = typecast(int8(digest.digest()), "uint8");
key = lower(string(reshape(dec2hex(raw, 2).', 1, [])));
end
