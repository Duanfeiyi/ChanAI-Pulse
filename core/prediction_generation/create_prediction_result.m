function result = create_prediction_result(request, cirDataset, ctfDataset, ...
        analysis, diagnostics, combinationManifest, cacheKey)
%CREATE_PREDICTION_RESULT Build canonical Step 11 product output.

arguments
    request (1, 1) struct
    cirDataset (1, 1) struct
    ctfDataset (1, 1) struct
    analysis (1, 1) struct
    diagnostics (:, 1) struct
    combinationManifest (1, 1) struct
    cacheKey (1, 1) string
end

cirValidation = validate_channel_dataset(cirDataset);
if ~cirValidation.is_valid
    error("create_prediction_result:InvalidCIR", ...
        "Combined CIR failed validation: %s", ...
        strjoin(cirValidation.errors, " | "));
end
ctfValidation = struct();
if ~isempty(fieldnames(ctfDataset))
    ctfValidation = validate_channel_dataset(ctfDataset);
    if ~ctfValidation.is_valid
        error("create_prediction_result:InvalidCTF", ...
            "CTF failed validation: %s", ...
            strjoin(ctfValidation.errors, " | "));
    end
end

capabilities = infer_channel_capabilities(cirDataset);
if isfield(analysis, "continuity_policy")
    for id = analysis.continuity_policy.blocked_metric_ids
        if isfield(capabilities, id)
            capabilities.(id) = false;
        end
    end
end
result = struct( ...
    "schema_version", "v3.0-prediction-result.1", ...
    "created_utc", utcNow(), ...
    "task_type", request.task_type, ...
    "task_axis", request.task_axis, ...
    "target_parameter_sample_index", ...
        double(request.target_parameter_sample_index(:)), ...
    "target_axis_values", double(request.target_axis_values(:)), ...
    "parameter_names", request.parameter_names, ...
    "parameter_units", request.parameter_units, ...
    "predicted_parameters", request.predicted_parameters, ...
    "cir_dataset", cirDataset, ...
    "ctf_dataset", ctfDataset, ...
    "analysis", analysis, ...
    "capabilities", capabilities, ...
    "dimensions", struct( ...
        "requested", request.dimensions, ...
        "cir_actual", cirDataset.dimensions, ...
        "ctf_actual", outputDimensions(ctfDataset)), ...
    "prediction_manifest", request.prediction_manifest, ...
    "generator_manifest", struct( ...
        "backend", request.backend, ...
        "mode", request.mode, ...
        "engine", request.engine, ...
        "scenario", request.scenario, ...
        "master_seed", request.master_seed, ...
        "parameter_sources", request.parameter_sources, ...
        "target_diagnostics", diagnostics, ...
        "combination", combinationManifest), ...
    "validation", struct( ...
        "cir", cirValidation, ...
        "ctf", ctfValidation), ...
    "cache_key", cacheKey);
end

function dimensions = outputDimensions(dataset)
dimensions = struct();
if isstruct(dataset) && isscalar(dataset) && ...
        isfield(dataset, "dimensions")
    dimensions = dataset.dimensions;
end
end

function value = utcNow()
value = string(datetime("now", "TimeZone", "UTC", ...
    "Format", "yyyy-MM-dd'T'HH:mm:ss.SSS'Z'"));
end
