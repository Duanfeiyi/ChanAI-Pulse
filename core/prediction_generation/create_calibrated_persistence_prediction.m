function prediction = create_calibrated_persistence_prediction( ...
        calibrationResult, task, backend)
%CREATE_CALIBRATED_PERSISTENCE_PREDICTION Safe v3.0 product baseline.
%   Converts only Module 2's known-region calibration into a target-free
%   Persistence prediction.  It deliberately does not inspect the target
%   region of the uploaded channel.  The function is the formal v3.0
%   fallback selected by the frozen Step 11ABC registry; neural models are
%   promoted only after the v3.1 offline acceptance gate.

arguments
    calibrationResult (1, 1) struct
    task (1, 1) struct
    backend (1, 1) string = "lite_6gpcm"
end

if ~isfield(calibrationResult, "success") || ~calibrationResult.success || ...
        ~isfield(calibrationResult, "best") || ...
        ~isfield(calibrationResult.best, "parameters")
    error("create_calibrated_persistence_prediction:NoCalibration", ...
        "A successful Module 2 calibration is required before prediction.");
end
if ~isfield(task, "target_indices") || isempty(task.target_indices)
    error("create_calibrated_persistence_prediction:NoTarget", ...
        "The task must declare one or more target indices.");
end

if isfield(task, "task_type")
    taskType = string(task.task_type);
elseif isfield(task, "mode")
    taskType = string(task.mode);
else
    error("create_calibrated_persistence_prediction:MissingTaskType", ...
        "The task must declare task_type or mode.");
end
if taskType == "extrapolation"
    parameterNames = ["DS_mu", "KF_mu", "DS_sigma", "KF_sigma", ...
        "r_DS", "LNS_ksi"];
elseif taskType == "interpolation"
    parameterNames = ["DS_mu", "KF_mu", "DS_sigma", "KF_sigma", ...
        "r_DS", "LNS_ksi", "num_clusters", "num_rays"];
else
    error("create_calibrated_persistence_prediction:UnsupportedTask", ...
        "Unsupported task type: %s.", taskType);
end

generator = default_generator_config(backend);
model = generator.model;
calibrated = calibrationResult.best.parameters;
for name = string(fieldnames(calibrated)).'
    model.(name) = calibrated.(name);
end

values = zeros(numel(task.target_indices), numel(parameterNames));
for column = 1:numel(parameterNames)
    name = parameterNames(column);
    if ~isfield(model, name) || ~isfinite(double(model.(name)))
        error("create_calibrated_persistence_prediction:MissingParameter", ...
            "Calibration/default configuration does not provide %s.", name);
    end
    values(:, column) = double(model.(name));
end

prediction = struct( ...
    "schema_version", "v3.0-calibrated-persistence-prediction.1", ...
    "task_type", taskType, ...
    "parameter_names", parameterNames(:), ...
    "parameter_units", parameterUnits(parameterNames(:)), ...
    "prediction_parameters", reshape(values, [1, size(values, 1), size(values, 2)]), ...
    "target_parameter_sample_index", reshape( ...
        double(task.target_indices(:)).', [1, numel(task.target_indices)]), ...
    "selection", struct( ...
        "mode", "auto", ...
        "selected_model_type", "persistence", ...
        "source", "step11abc_frozen_registry", ...
        "reason", "No neural candidate has passed the v3.1 promotion gate."), ...
    "adaptation", struct( ...
        "mode", "off", ...
        "performed", false, ...
        "reason", "v3.0 product baseline uses known-region calibration only."), ...
    "model", struct( ...
        "model_type", "persistence", ...
        "implementation", "module2_calibrated_constant", ...
        "calibration_manifest_schema", calibrationResult.manifest.schema_version), ...
    "request_contains_target_ground_truth", false, ...
    "provenance", struct( ...
        "source", "module2_known_region_calibration", ...
        "target_values_read", false, ...
        "calibration_strategy", selectedStrategy(calibrationResult)));
end

function units = parameterUnits(names)
units = strings(numel(names), 1);
for index = 1:numel(names)
    switch names(index)
        case {"DS_mu", "DS_sigma"}
            units(index) = "log10(s)";
        case {"KF_mu", "KF_sigma", "LNS_ksi"}
            units(index) = "dB";
        case "r_DS"
            units(index) = "ratio";
        case {"num_clusters", "num_rays"}
            units(index) = "count";
        otherwise
            units(index) = "unspecified";
    end
end

end

function value = selectedStrategy(result)
value = "unspecified";
if isfield(result, "selected_strategy")
    value = string(result.selected_strategy);
end
end
