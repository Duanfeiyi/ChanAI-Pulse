function config = default_experiment_manager_config(assetRoot)
%DEFAULT_EXPERIMENT_MANAGER_CONFIG Defaults for the v3.1-2 local manager.

arguments
    assetRoot (1, 1) string = ""
end
repositoryRoot = fileparts(fileparts(fileparts(mfilename("fullpath"))));
config = struct( ...
    "schema_version", "v3.1-2-experiment-manager-config.1", ...
    "asset_root", assetRoot, ...
    "repository_root", string(repositoryRoot), ...
    "experiment_subdirectory", "experiments", ...
    "status_values", ["pending", "running", "completed", "failed"], ...
    "path_policy", "local_asset_root_only", ...
    "overwrite_policy", "refuse_existing_experiment_id", ...
    "track_private_data", false);
end
