function [details, summary, manifest] = run_v31_6_full_benchmark( ...
        pairCsv, exportManifestPath, protocolConfigPath, outputDirectory, options)
%RUN_V31_6_FULL_BENCHMARK Frozen two-stage v3.1-6 channel-level benchmark.
%   Validation creates the gate consumed by the create-once Test export.
%   Full 6GPCM is always accessed through its read-only public adapter.

arguments
    pairCsv (1, 1) string
    exportManifestPath (1, 1) string
    protocolConfigPath (1, 1) string
    outputDirectory (1, 1) string
    options.Backend (1, 1) string = "full_6gpcm"
    options.Mode (1, 1) string {mustBeMember(options.Mode, ["preview", "formal"])} = "formal"
    options.ValidationGate (1, 1) string = ""
    options.AllowResume (1, 1) logical = true
end
clock = tic;
config = jsondecode(fileread(protocolConfigPath));
exportManifest = jsondecode(fileread(exportManifestPath));
validateInputs(pairCsv, exportManifestPath, protocolConfigPath, ...
    config, exportManifest, options);
partition = string(exportManifest.evaluation_partition);
if ~isfolder(outputDirectory), mkdir(outputDirectory); end
detailPath = fullfile(outputDirectory, "v31_6_" + partition + "_channel_rows.csv");
if isfile(detailPath) && options.AllowResume
    details = readtable(detailPath, TextType="string", VariableNamingRule="preserve");
else
    if isfile(detailPath)
        error("run_v31_6_full_benchmark:OutputExists", ...
            "Detailed output exists and resume is disabled.");
    end
    details = table();
end
pairs = readtable(pairCsv, TextType="string", VariableNamingRule="preserve");
requireColumns(pairs);
expectedPairs = 110;
if partition == "test", expectedPairs = 660; end
if height(pairs) ~= expectedPairs
    error("run_v31_6_full_benchmark:IncompletePairMatrix", ...
        "Frozen %s matrix has %d pairs; expected %d.", ...
        partition, height(pairs), expectedPairs);
end
fullRoot = resolve_full_6gpcm_root();
treeBefore = "not_applicable_mock";
if options.Backend == "full_6gpcm"
    treeBefore = hash_full_6gpcm_tree(fullRoot.root).aggregate_sha256;
end
truthCache = containers.Map("KeyType", "char", "ValueType", "any");
completed = completedKeys(details);
for index = 1:height(pairs)
    row = pairs(index, :);
    identity = rowKey(row);
    if isKey(completed, identity), continue; end
    truthKey = sprintf('%s|%s|%.0f|%.0f', row.task_type, row.group_id, ...
        row.target_step, row.protocol_seed);
    truthConfig = generatorConfig(row, config, options, "truth");
    if isKey(truthCache, truthKey)
        truth = truthCache(truthKey);
    else
        truth = requireSuccess(run_generator_adapter(truthConfig));
        truthCache(truthKey) = truth;
    end
    predictionConfig = generatorConfig(row, config, options, "predicted");
    prediction = requireSuccess(run_generator_adapter(predictionConfig));
    metricClock = tic;
    metrics = compare_v31_6_channels(truth, prediction, ...
        double(config.generator_evaluation.delay_bin_count));
    details = [details; metricRow(row, metrics, truth, prediction, ...
        toc(metricClock))]; %#ok<AGROW>
    completed(identity) = true;
    writetable(details, detailPath);
end
summary = summarizeRows(details, config);
summaryPath = fullfile(outputDirectory, ...
    "v31_6_" + partition + "_channel_summary.csv");
writetable(summary, summaryPath);
treeAfter = treeBefore;
if options.Backend == "full_6gpcm"
    treeAfter = hash_full_6gpcm_tree(fullRoot.root).aggregate_sha256;
    if treeBefore ~= treeAfter
        error("run_v31_6_full_benchmark:CoreChanged", ...
            "The bundled Full 6GPCM core changed during evaluation.");
    end
end
manifest = makeManifest(partition, pairCsv, exportManifestPath, ...
    protocolConfigPath, detailPath, summaryPath, config, exportManifest, ...
    treeBefore, treeAfter, options, toc(clock), details);
manifestPath = fullfile(outputDirectory, ...
    "v31_6_" + partition + "_benchmark_manifest.json");
writeJson(manifestPath, manifest);
if partition == "validation"
    gate = makeGate(manifest, protocolConfigPath, exportManifestPath, details);
    writeJson(fullfile(outputDirectory, "v31_6_validation_gate.json"), gate);
end
end

function validateInputs(pairCsv, exportPath, configPath, config, manifest, options)
if string(config.schema_version) ~= "v3.1-6-end-to-end-config.1"
    error("run_v31_6_full_benchmark:ConfigSchema", "Unsupported protocol config.");
end
if string(manifest.schema_version) ~= "v3.1-6-parameter-export.1"
    error("run_v31_6_full_benchmark:ExportSchema", "Unsupported parameter export.");
end
if compute_benchmark_file_sha256(configPath) ~= string(manifest.protocol_config_sha256)
    error("run_v31_6_full_benchmark:ConfigHash", "Protocol config hash mismatch.");
end
if compute_benchmark_file_sha256(pairCsv) ~= string(manifest.generator_pairs_sha256)
    error("run_v31_6_full_benchmark:PairHash", "Generator pair CSV hash mismatch.");
end
if ~isfile(exportPath), error("Missing export manifest."); end
partition = string(manifest.evaluation_partition);
if ~ismember(partition, ["validation", "test"])
    error("run_v31_6_full_benchmark:Partition", "Unsupported partition.");
end
if options.Backend ~= "full_6gpcm" && options.Mode ~= "preview"
    error("run_v31_6_full_benchmark:MockFormal", ...
        "Only Full 6GPCM may produce formal evidence.");
end
if partition == "test"
    if strlength(options.ValidationGate) == 0 || ~isfile(options.ValidationGate)
        error("run_v31_6_full_benchmark:MissingGate", ...
            "Formal Test evaluation requires the frozen validation gate.");
    end
    gate = jsondecode(fileread(options.ValidationGate));
    if string(gate.schema_version) ~= "v3.1-6-validation-gate.1" || ...
            ~logical(gate.passed) || string(gate.protocol_config_sha256) ~= ...
            compute_benchmark_file_sha256(configPath) || logical(gate.test_partition_used)
        error("run_v31_6_full_benchmark:InvalidGate", ...
            "The supplied validation gate is invalid or belongs to another protocol.");
    end
    if ~isfield(manifest, "validation_gate") || ...
            ~isfield(manifest.validation_gate, "sha256") || ...
            string(manifest.validation_gate.sha256) ~= ...
            compute_benchmark_file_sha256(options.ValidationGate)
        error("run_v31_6_full_benchmark:GateHashMismatch", ...
            "The supplied gate is not the exact gate bound into the Test export.");
    end
    if ~isfield(manifest.validation_gate, "payload") || ...
            string(manifest.validation_gate.payload.protocol_config_sha256) ~= ...
            string(gate.protocol_config_sha256)
        error("run_v31_6_full_benchmark:GatePayloadMismatch", ...
            "The Test export gate payload does not match the supplied gate.");
    end
end
end

function requireColumns(rows)
required = ["partition", "task_type", "candidate_id", "selected_model", ...
    "registry_recommended_model", "group_id", "target_step", ...
    "protocol_seed", "scenario_name", "carrier_frequency_hz", ...
    "route_speed_mps", "tx_count", "rx_count"];
names = ["DS_mu", "KF_mu", "DS_sigma", "KF_sigma", ...
    "r_DS", "LNS_ksi", "num_clusters", "num_rays"];
required = [required, "truth_" + names, "predicted_" + names];
missing = setdiff(required, string(rows.Properties.VariableNames));
if ~isempty(missing)
    error("run_v31_6_full_benchmark:MissingColumns", ...
        "Pair CSV misses: %s", strjoin(missing, ", "));
end
end

function configOut = generatorConfig(row, protocol, options, prefix)
configOut = default_generator_config(options.Backend);
configOut.mode = options.Mode;
if options.Backend == "full_6gpcm"
    configOut.backend_options.full_interface = "public_api";
end
configOut.backend_options.full_track_speed_mps = double(row.route_speed_mps);
g = protocol.generator_evaluation;
configOut.dimensions = struct("Tx", double(row.tx_count), ...
    "Rx", double(row.rx_count), "Npath", 0, ...
    "Nt", double(g.snapshot_count), "N_sample", 1);
if options.Backend == "mock"
    configOut.dimensions.Npath = 12;
end
configOut.scenario.id = string(row.scenario_name);
configOut.scenario.center_frequency_hz = double(row.carrier_frequency_hz);
configOut.scenario.bandwidth_hz = double(g.bandwidth_hz);
configOut.scenario.track_type = "linear";
configOut.scenario.snapshot_interval_s = double(g.snapshot_interval_s);
configOut.ctf.enabled = true;
configOut.ctf.frequency_hz = linspace( ...
    double(row.carrier_frequency_hz) - double(g.bandwidth_hz) / 2, ...
    double(row.carrier_frequency_hz) + double(g.bandwidth_hz) / 2, ...
    double(g.ctf_frequency_count)).';
configOut.random_seed = derivedSeed(double(row.protocol_seed), ...
    string(row.group_id), double(row.target_step));
names = ["DS_mu", "KF_mu", "DS_sigma", "KF_sigma", ...
    "r_DS", "LNS_ksi", "num_clusters", "num_rays"];
for index = 1:numel(names)
    configOut.model.(names(index)) = double(row.(prefix + "_" + names(index)));
end
end

function seed = derivedSeed(base, group, target)
bytes = unicode2native(char(group), 'UTF-8');
weight = mod(sum(double(bytes) .* (1:numel(bytes))), 100000);
seed = mod(round(base) + weight + 97 * round(target), 2^31 - 2) + 1;
end

function result = requireSuccess(result)
if ~result.success
    error("run_v31_6_full_benchmark:GenerationFailed", ...
        "%s", strjoin(result.errors, " | "));
end
end

function row = metricRow(source, metrics, truth, prediction, runtime)
row = table(string(source.partition), string(source.task_type), ...
    string(source.candidate_id), string(source.selected_model), ...
    string(source.registry_recommended_model), string(source.group_id), ...
    double(source.target_step), double(source.protocol_seed), ...
    parseBoolean(source.is_stability_subset), double(source.parameter_nrmse), ...
    double(source.sensitivity_weighted_nrmse), metrics.complex_nmse, ...
    metrics.complex_nrmse, metrics.magnitude_nrmse, metrics.phase_mae_rad, ...
    metrics.complex_correlation, metrics.pdp_nrmse, ...
    metrics.rms_delay_spread_abs_error_s, metrics.spatial_correlation_delta, ...
    metrics.temporal_coherence_delta, metrics.frequency_coherence_delta, ...
    metrics.doppler_power_nrmse, metrics.angular_metric_available, ...
    metrics.angular_spectrum_nrmse, ...
    double(truth.runtime.elapsed_s), double(prediction.runtime.elapsed_s), runtime, ...
    coreHash(truth), coreHash(prediction), ...
    'VariableNames', {'partition', 'task_type', 'candidate_id', ...
    'selected_model', 'registry_recommended_model', 'group_id', ...
    'target_step', 'protocol_seed', 'is_stability_subset', ...
    'parameter_nrmse', 'sensitivity_weighted_nrmse', 'complex_nmse', ...
    'complex_nrmse', 'magnitude_nrmse', 'phase_mae_rad', ...
    'complex_correlation', 'pdp_nrmse', ...
    'rms_delay_spread_abs_error_s', 'spatial_correlation_delta', ...
    'temporal_coherence_delta', 'frequency_coherence_delta', ...
    'doppler_power_nrmse', 'angular_metric_available', ...
    'angular_spectrum_nrmse', 'truth_generation_runtime_s', ...
    'prediction_generation_runtime_s', 'metric_runtime_s', ...
    'truth_core_tree_sha256', 'prediction_core_tree_sha256'});
end

function value = parseBoolean(input)
if islogical(input) || isnumeric(input)
    value = logical(input);
else
    normalized = lower(strtrim(string(input)));
    if normalized == "true" || normalized == "1"
        value = true;
    elseif normalized == "false" || normalized == "0"
        value = false;
    else
        error("run_v31_6_full_benchmark:InvalidBoolean", ...
            "Cannot parse boolean value: %s", normalized);
    end
end
end

function value = coreHash(result)
value = "not_applicable";
if isfield(result, "backend_manifest") && ...
        isfield(result.backend_manifest, "tree_sha256_after")
    value = string(result.backend_manifest.tree_sha256_after);
end
end

function keys = completedKeys(details)
keys = containers.Map("KeyType", "char", "ValueType", "logical");
for index = 1:height(details), keys(rowKey(details(index, :))) = true; end
end

function value = rowKey(row)
value = sprintf('%s|%s|%s|%.0f|%.0f', row.task_type, row.candidate_id, ...
    row.group_id, row.target_step, row.protocol_seed);
end

function summary = summarizeRows(details, protocol)
summary = table();
tasks = unique(details.task_type, 'stable');
candidates = unique(details.candidate_id, 'stable');
rng(31606, "twister");
for taskIndex = 1:numel(tasks)
    for candidateIndex = 1:numel(candidates)
        mask = details.task_type == tasks(taskIndex) & ...
            details.candidate_id == candidates(candidateIndex);
        selected = details(mask, :);
        if isempty(selected), continue; end
        routeMeans = groupsummary(selected, 'group_id', 'mean', ...
            {'complex_nmse', 'pdp_nrmse', 'parameter_nrmse', ...
            'sensitivity_weighted_nrmse'});
        values = double(routeMeans.mean_complex_nmse);
        ci = bootstrapMeanCi(values, 2000);
        recommended = string(selected.registry_recommended_model(1));
        winRate = recommendedWinRate(details, selected, recommended);
        eligible = ismember(string(selected.candidate_id(1)), ...
            ["persistence", "linear", "ar", "kalman"]);
        row = table(tasks(taskIndex), candidates(candidateIndex), ...
            string(selected.selected_model(1)), recommended, eligible, ...
            height(selected), height(routeMeans), mean(values), std(values), ...
            median(values), percentile(values, 90), percentile(values, 95), ...
            ci(1), ci(2), mean(routeMeans.mean_pdp_nrmse), ...
            mean(routeMeans.mean_parameter_nrmse), ...
            mean(routeMeans.mean_sensitivity_weighted_nrmse), winRate, ...
            'VariableNames', {'task_type', 'candidate_id', 'selected_model', ...
            'registry_recommended_model', 'eligible_to_upgrade_auto_default', ...
            'pair_count', 'route_count', 'mean_complex_nmse', ...
            'std_complex_nmse', 'median_complex_nmse', 'p90_complex_nmse', ...
            'p95_complex_nmse', 'bootstrap_ci95_lower', ...
            'bootstrap_ci95_upper', 'mean_pdp_nrmse', ...
            'mean_parameter_nrmse', 'mean_sensitivity_weighted_nrmse', ...
            'route_win_rate_vs_recommended'});
        summary = [summary; row]; %#ok<AGROW>
    end
end
summary.protocol_id(:) = string(protocol.protocol_id);
end

function value = recommendedWinRate(allRows, selected, recommended)
if string(selected.candidate_id(1)) == recommended, value = 0.5; return; end
wins = 0; comparable = 0;
for index = 1:height(selected)
    row = selected(index, :);
    mask = allRows.task_type == row.task_type & ...
        allRows.candidate_id == recommended & allRows.group_id == row.group_id & ...
        allRows.target_step == row.target_step & ...
        allRows.protocol_seed == row.protocol_seed;
    if nnz(mask) == 1
        comparable = comparable + 1;
        wins = wins + double(row.complex_nmse < allRows.complex_nmse(mask));
    end
end
value = wins / max(1, comparable);
end

function ci = bootstrapMeanCi(values, repeats)
values = double(values(:));
if isscalar(values), ci = [values, values]; return; end
means = zeros(repeats, 1);
for index = 1:repeats
    means(index) = mean(values(randi(numel(values), numel(values), 1)));
end
ci = [percentile(means, 2.5), percentile(means, 97.5)];
end

function value = percentile(values, percent)
values = sort(double(values(:)));
position = 1 + (numel(values) - 1) * percent / 100;
lower = floor(position); upper = ceil(position);
value = values(lower) + (position - lower) * (values(upper) - values(lower));
end

function manifest = makeManifest(partition, pairCsv, exportPath, configPath, ...
        detailPath, summaryPath, config, exportManifest, before, after, ...
        options, runtime, details)
manifest = struct( ...
    "schema_version", "v3.1-6-channel-benchmark-result.1", ...
    "created_utc", string(datetime("now", "TimeZone", "UTC", ...
        "Format", "yyyy-MM-dd'T'HH:mm:ss.SSSXXX")), ...
    "protocol_id", string(config.protocol_id), ...
    "evaluation_partition", partition, ...
    "protocol_config_sha256", compute_benchmark_file_sha256(configPath), ...
    "parameter_export_manifest_sha256", compute_benchmark_file_sha256(exportPath), ...
    "generator_pairs_sha256", compute_benchmark_file_sha256(pairCsv), ...
    "channel_rows_sha256", compute_benchmark_file_sha256(detailPath), ...
    "channel_summary_sha256", compute_benchmark_file_sha256(summaryPath), ...
    "backend", options.Backend, "mode", options.Mode, ...
    "full_6gpcm_tree_sha256_before", before, ...
    "full_6gpcm_tree_sha256_after", after, ...
    "full_6gpcm_core_unchanged", before == after, ...
    "pair_count", height(details), "runtime_s", runtime, ...
    "test_partition_used_for_model_selection", false, ...
    "registry_or_threshold_changed", false, ...
    "source_export", exportManifest.schema_version, ...
    "angular_metrics", "not_available_public_adapter_no_ray_angles", ...
    "time_metric_note", "Nt=4 short-window diagnostic; not a long Doppler study");
end

function gate = makeGate(manifest, configPath, exportPath, details)
passed = height(details) > 0 && all(isfinite(details.complex_nmse)) && ...
    all(isfinite(details.pdp_nrmse)) && logical(manifest.full_6gpcm_core_unchanged);
gate = struct( ...
    "schema_version", "v3.1-6-validation-gate.1", ...
    "created_utc", manifest.created_utc, "passed", passed, ...
    "evaluation_partition", "validation", "test_partition_used", false, ...
    "protocol_config_sha256", compute_benchmark_file_sha256(configPath), ...
    "validation_export_manifest_sha256", compute_benchmark_file_sha256(exportPath), ...
    "validation_pair_count", height(details), ...
    "all_primary_metrics_finite", passed, ...
    "full_6gpcm_core_unchanged", manifest.full_6gpcm_core_unchanged, ...
    "selection_is_frozen_before_test", true, ...
    "thresholds_are_frozen_before_test", true);
end

function writeJson(path, payload)
text = jsonencode(payload, PrettyPrint=true);
file = fopen(path, 'w');
if file < 0, error("Cannot create JSON output: %s", path); end
cleanup = onCleanup(@() fclose(file)); %#ok<NASGU>
fwrite(file, text, 'char');
end
